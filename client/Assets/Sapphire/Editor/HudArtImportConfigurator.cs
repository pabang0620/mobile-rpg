            ArtImportConfigurator.ConfigureSingleSprite(
                SapphireSceneBuilder.UiArtDir + "/MenuHamburgerIcon.png",
                border: Vector4.zero,
                filterMode: FilterMode.Bilinear,
                mipmaps: false,
                pixelsPerUnit: ArtImportConfigurator.UiKitV3PixelsPerUnit);
        }

